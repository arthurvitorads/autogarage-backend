-- Origem: db-scripts/Atualizacoes/003_tempo_item_os.sql
-- Campos de controle por item. Registros antigos não recebem tempo retroativo.
alter table ord_item_os add column if not exists ca_status_servico text not null default 'PENDENTE'
  check (ca_status_servico in ('PENDENTE', 'EM_ANDAMENTO', 'PAUSADO', 'FINALIZADO', 'CANCELADO'));
alter table ord_item_os add column if not exists qt_tempo_segundos integer not null default 0 check (qt_tempo_segundos >= 0);
alter table ord_item_os add column if not exists dt_inicio_tempo timestamptz;
create index if not exists idx_ord_item_os_4
  on ord_item_os (ca_status_servico, qt_tempo_segundos);

-- Origem: db-scripts/Tabelas/ord_tempo_item_os.sql
create table if not exists ord_tempo_item_os (
  cn_tempo_item_os bigint generated by default as identity primary key,
  cn_item          bigint not null,
  dt_inicio        timestamptz not null,
  dt_fim           timestamptz,
  qt_segundos      integer not null default 0 check (qt_segundos >= 0),
  ca_encerramento  text check (ca_encerramento in ('PAUSAR', 'FINALIZAR', 'CANCELAR')),
  dt_inc           timestamptz not null default now(),
  dt_alt           timestamptz not null default now(),
  constraint fk_ord_tempo_item_os_1 foreign key (cn_item)
    references ord_item_os (cn_item) on delete restrict on update cascade,
  constraint ck_ord_tempo_item_os_1 check (
    (dt_fim is null and ca_encerramento is null and qt_segundos = 0) or
    (dt_fim is not null and dt_fim >= dt_inicio and ca_encerramento is not null and
      qt_segundos = floor(extract(epoch from (dt_fim - dt_inicio))))
  )
);

create index if not exists idx_ord_tempo_item_os_1
  on ord_tempo_item_os (cn_item);

create unique index if not exists idx_ord_tempo_item_os_2
  on ord_tempo_item_os (cn_item) where dt_fim is null;

-- Origem: db-scripts/Tabelas/fat_venda.sql
create table if not exists fat_venda (
  cn_venda           bigint generated by default as identity primary key,
  nu_numero          integer generated by default as identity not null unique,
  cn_pessoa          bigint not null,
  cn_ordem_servico   bigint unique,
  ca_chave_requisicao text not null unique,
  ca_hash_requisicao  text not null,
  ca_origem          text not null check (ca_origem in ('ORDEM_SERVICO', 'DIRETA')),
  an_cliente         text not null,
  ca_documento       text not null,
  an_email           text not null default '',
  an_telefone        text not null default '',
  an_endereco        text not null default '',
  an_obs             text not null default '',
  ca_id_firebase     text not null,
  dt_venda           timestamptz not null default now(),
  vl_total           numeric(20,2) not null check (vl_total >= 0),
  dt_inc             timestamptz not null default now(),
  dt_alt             timestamptz not null default now(),
  constraint fk_fat_venda_1 foreign key (cn_pessoa)
    references cad_pessoa (cn_pessoa) on delete restrict on update cascade,
  constraint fk_fat_venda_2 foreign key (cn_ordem_servico)
    references ord_ordem_servico (cn_ordem_servico) on delete restrict on update cascade,
  constraint ck_fat_venda_1 check (
    (ca_origem = 'ORDEM_SERVICO' and cn_ordem_servico is not null) or
    (ca_origem = 'DIRETA' and cn_ordem_servico is null)
  )
);

create index if not exists idx_fat_venda_1
  on fat_venda (cn_pessoa);

create index if not exists idx_fat_venda_2
  on fat_venda (dt_venda);

-- Origem: db-scripts/Tabelas/fat_item_venda.sql
create table if not exists fat_item_venda (
  cn_item_venda     bigint generated by default as identity primary key,
  cn_venda          bigint not null,
  cn_item_os        bigint unique,
  ca_tipo           text not null check (ca_tipo in ('PRODUTO', 'SERVICO')),
  cn_produto        integer,
  cn_servico        integer,
  an_descr          text not null,
  ca_unidade        text not null default '',
  qt_quantidade     numeric(12,3) not null check (qt_quantidade > 0),
  vl_unitario       numeric(11,2) not null check (vl_unitario >= 0),
  vl_custo          numeric(11,2) not null check (vl_custo >= 0),
  vl_total          numeric(20,2) not null check (vl_total = round(qt_quantidade * vl_unitario, 2)),
  qt_tempo_segundos integer not null default 0 check (qt_tempo_segundos >= 0),
  dt_inc            timestamptz not null default now(),
  dt_alt            timestamptz not null default now(),
  constraint fk_fat_item_venda_1 foreign key (cn_venda)
    references fat_venda (cn_venda) on delete restrict on update cascade,
  constraint fk_fat_item_venda_2 foreign key (cn_item_os)
    references ord_item_os (cn_item) on delete restrict on update cascade,
  constraint fk_fat_item_venda_3 foreign key (cn_produto)
    references cad_produto (cn_produto) on delete restrict on update cascade,
  constraint fk_fat_item_venda_4 foreign key (cn_servico)
    references cad_servico (cn_servico) on delete restrict on update cascade,
  constraint ck_fat_item_venda_1 check (
    (ca_tipo = 'PRODUTO' and cn_produto is not null and cn_servico is null) or
    (ca_tipo = 'SERVICO' and cn_servico is not null and cn_produto is null)
