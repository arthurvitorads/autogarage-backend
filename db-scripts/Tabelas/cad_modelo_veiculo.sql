create table if not exists cad_modelo_veiculo (
  cn_modelo_veiculo integer generated by default as identity primary key,
  cn_marca_veiculo integer not null references cad_marca_veiculo (cn_marca_veiculo)
    on delete restrict on update cascade,
  an_descr text not null,
  ca_chave text not null,
  unique (cn_marca_veiculo, ca_chave)
);

comment on column cad_modelo_veiculo.cn_modelo_veiculo is 'Identificador do modelo do veículo.';
comment on column cad_modelo_veiculo.cn_marca_veiculo is 'Marca à qual o modelo pertence.';
comment on column cad_modelo_veiculo.an_descr is 'Nome de exibição do modelo do veículo.';
comment on column cad_modelo_veiculo.ca_chave is 'Nome normalizado usado para identificar o modelo dentro da marca.';
