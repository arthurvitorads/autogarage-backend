create table if not exists end_estados (
  cn_estado       bigint generated by default as identity primary key,
  an_descr        text not null,
  ca_uf           text not null,
  ca_pais         varchar(2) not null,
  dt_inc          timestamptz not null default now(),
  dt_alt          timestamptz not null default now()
);

create unique index if not exists idx_end_estados_1
  on end_estados (ca_pais, ca_uf);
