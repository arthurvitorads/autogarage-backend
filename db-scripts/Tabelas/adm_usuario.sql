create table adm_usuario (
  cn_usuario      bigint generated by default as identity primary key,
  ca_id_firebase  text not null unique,
  an_email        text not null,
  an_nome         text not null,
  cn_perfil       bigint,
  bo_sts_reg      boolean not null default true,
  dt_inc          timestamptz not null default now(),
  dt_alt          timestamptz not null default now()
);

create index if not exists idx_adm_usuario_1
    on adm_usuario (an_email);

create index if not exists idx_adm_usuario_2
    on adm_usuario (dt_inc);

create index if not exists idx_adm_usuario_3
  on adm_usuario (cn_perfil);

alter table adm_usuario
  add constraint fk_adm_usuario_1
  foreign key (cn_perfil)
  references adm_perfil (cn_perfil)
  on delete restrict
  on update cascade;

comment on column adm_usuario.cn_usuario is 'Identificador do usuário.';
comment on column adm_usuario.ca_id_firebase is 'Identificador do usuário no Firebase Authentication.';
comment on column adm_usuario.an_email is 'Endereço de e-mail.';
comment on column adm_usuario.an_nome is 'Nome do usuário.';
comment on column adm_usuario.cn_perfil is 'Identificador do perfil de acesso.';
comment on column adm_usuario.bo_sts_reg is 'Indica se o registro está ativo.';
comment on column adm_usuario.dt_inc is 'Data e hora de inclusão.';
comment on column adm_usuario.dt_alt is 'Data e hora da última alteração.';
