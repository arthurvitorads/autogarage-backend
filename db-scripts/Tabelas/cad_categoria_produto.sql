create table if not exists cad_categoria_produto (
  cn_categoria_produto integer generated by default as identity primary key,
  an_descr text not null,
  dt_inc   timestamptz not null default now(),
  dt_alt   timestamptz not null default now()
);

create unique index if not exists idx_cad_categoria_produto_1
  on cad_categoria_produto (lower(btrim(an_descr)));
