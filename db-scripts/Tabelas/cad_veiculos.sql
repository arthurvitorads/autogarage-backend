create table if not exists cad_veiculos (
  cn_veiculo bigint generated by default as identity primary key,
  an_placa text not null unique check (an_placa ~ '^[A-Z]{3}[0-9][A-Z0-9][0-9]{2}$'),
  cn_modelo_veiculo integer not null references cad_modelo_veiculo (cn_modelo_veiculo)
    on delete restrict on update cascade,
  nu_ano integer,
  an_cor text not null default '',
  dt_inc timestamptz not null default now(),
  dt_alt timestamptz not null default now()
);

create index if not exists idx_cad_veiculos_modelo on cad_veiculos (cn_modelo_veiculo);

comment on column cad_veiculos.cn_veiculo is 'Identificador do veículo no cadastro interno.';
comment on column cad_veiculos.an_placa is 'Placa sem máscara, usada na consulta de veículos.';
comment on column cad_veiculos.cn_modelo_veiculo is 'Modelo vinculado ao veículo.';
comment on column cad_veiculos.nu_ano is 'Ano do veículo informado no cadastro.';
comment on column cad_veiculos.an_cor is 'Cor do veículo informada no cadastro.';
comment on column cad_veiculos.dt_inc is 'Data e hora de inclusão.';
comment on column cad_veiculos.dt_alt is 'Data e hora da última alteração.';
