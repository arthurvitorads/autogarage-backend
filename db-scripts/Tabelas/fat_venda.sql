create table if not exists fat_venda (
  cn_venda           bigint generated by default as identity primary key,
  nu_numero          integer generated by default as identity not null unique,
  cn_pessoa          bigint not null,
  cn_ordem_servico   bigint unique,
  ca_chave_requisicao text not null unique,
  ca_hash_requisicao  text not null,
  ca_origem          text not null check (ca_origem in ('ORDEM_SERVICO', 'DIRETA')),
  an_cliente         text not null,
  ca_documento       text not null,
  an_email           text not null default '',
  an_telefone        text not null default '',
  an_endereco        text not null default '',
  an_obs             text not null default '',
  ca_id_firebase     text not null,
  dt_venda           timestamptz not null default now(),
  vl_total           numeric(20,2) not null check (vl_total >= 0),
  dt_inc             timestamptz not null default now(),
  dt_alt             timestamptz not null default now(),
  constraint fk_fat_venda_1 foreign key (cn_pessoa)
    references cad_pessoa (cn_pessoa) on delete restrict on update cascade,
  constraint fk_fat_venda_2 foreign key (cn_ordem_servico)
    references ord_ordem_servico (cn_ordem_servico) on delete restrict on update cascade,
  constraint ck_fat_venda_1 check (
    (ca_origem = 'ORDEM_SERVICO' and cn_ordem_servico is not null) or
    (ca_origem = 'DIRETA' and cn_ordem_servico is null)
  )
);

create index if not exists idx_fat_venda_1
  on fat_venda (cn_pessoa);

create index if not exists idx_fat_venda_2
  on fat_venda (dt_venda);
