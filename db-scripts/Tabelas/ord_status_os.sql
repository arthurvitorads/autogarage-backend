create table ord_status_os (
  cn_status_os    bigint generated by default as identity primary key,
  an_descr        text,
  bo_sts_reg      boolean not null default true,
  dt_inc          timestamptz not null default now(),
  dt_alt          timestamptz not null default now()
);

create index if not exists idx_ord_status_os_1
  on ord_status_os (dt_inc);
