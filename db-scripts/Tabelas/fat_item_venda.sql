create table if not exists fat_item_venda (
  cn_item_venda     bigint generated by default as identity primary key,
  cn_venda          bigint not null,
  cn_item_os        bigint unique,
  ca_tipo           text not null check (ca_tipo in ('PRODUTO', 'SERVICO')),
  cn_produto        integer,
  cn_servico        integer,
  an_descr          text not null,
  ca_unidade        text not null default '',
  qt_quantidade     numeric(12,3) not null check (qt_quantidade > 0),
  vl_unitario       numeric(11,2) not null check (vl_unitario >= 0),
  vl_custo          numeric(11,2) not null check (vl_custo >= 0),
  vl_total          numeric(20,2) not null check (vl_total = round(qt_quantidade * vl_unitario, 2)),
  qt_tempo_segundos integer not null default 0 check (qt_tempo_segundos >= 0),
  dt_inc            timestamptz not null default now(),
  dt_alt            timestamptz not null default now(),
  constraint fk_fat_item_venda_1 foreign key (cn_venda)
    references fat_venda (cn_venda) on delete restrict on update cascade,
  constraint fk_fat_item_venda_2 foreign key (cn_item_os)
    references ord_item_os (cn_item) on delete restrict on update cascade,
  constraint fk_fat_item_venda_3 foreign key (cn_produto)
    references cad_produto (cn_produto) on delete restrict on update cascade,
  constraint fk_fat_item_venda_4 foreign key (cn_servico)
    references cad_servico (cn_servico) on delete restrict on update cascade,
  constraint ck_fat_item_venda_1 check (
    (ca_tipo = 'PRODUTO' and cn_produto is not null and cn_servico is null) or
    (ca_tipo = 'SERVICO' and cn_servico is not null and cn_produto is null)
  )
);

create index if not exists idx_fat_item_venda_1
  on fat_item_venda (cn_venda);

create index if not exists idx_fat_item_venda_2
  on fat_item_venda (cn_produto);

create index if not exists idx_fat_item_venda_3
  on fat_item_venda (cn_servico);
