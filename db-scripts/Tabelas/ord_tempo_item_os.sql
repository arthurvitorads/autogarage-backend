create table if not exists ord_tempo_item_os (
  cn_tempo_item_os bigint generated by default as identity primary key,
  cn_item          bigint not null,
  dt_inicio        timestamptz not null,
  dt_fim           timestamptz,
  qt_segundos      integer not null default 0 check (qt_segundos >= 0),
  ca_encerramento  text check (ca_encerramento in ('PAUSAR', 'FINALIZAR', 'CANCELAR')),
  dt_inc           timestamptz not null default now(),
  dt_alt           timestamptz not null default now(),
  constraint fk_ord_tempo_item_os_1 foreign key (cn_item)
    references ord_item_os (cn_item) on delete restrict on update cascade,
  constraint ck_ord_tempo_item_os_1 check (
    (dt_fim is null and ca_encerramento is null and qt_segundos = 0) or
    (dt_fim is not null and dt_fim >= dt_inicio and ca_encerramento is not null and
      qt_segundos = floor(extract(epoch from (dt_fim - dt_inicio))))
  )
);

create index if not exists idx_ord_tempo_item_os_1
  on ord_tempo_item_os (cn_item);

create unique index if not exists idx_ord_tempo_item_os_2
  on ord_tempo_item_os (cn_item) where dt_fim is null;
