create table if not exists ord_item_os (
  cn_item           bigint generated by default as identity primary key,
  cn_ordem_servico  bigint not null,
  ca_tipo           text not null check (ca_tipo in ('PRODUTO', 'SERVICO')),
  cn_produto        integer,
  cn_servico        integer,
  an_descr          text not null,
  ca_unidade        text not null default '',
  qt_quantidade     numeric(12,3) not null check (qt_quantidade > 0),
  vl_unitario       numeric(11,2) not null check (vl_unitario >= 0),
  vl_total          numeric(20,2) not null check (vl_total = round(qt_quantidade * vl_unitario, 2)),
  dt_inc            timestamptz not null default now(),
  dt_alt            timestamptz not null default now(),
  constraint fk_ord_item_os_1 foreign key (cn_ordem_servico) references ord_ordem_servico (cn_ordem_servico) on delete restrict on update cascade,
  constraint fk_ord_item_os_2 foreign key (cn_produto) references cad_produto (cn_produto) on delete restrict on update cascade,
  constraint fk_ord_item_os_3 foreign key (cn_servico) references cad_servico (cn_servico) on delete restrict on update cascade,
  constraint ck_ord_item_os_1 check (
    (ca_tipo = 'PRODUTO' and cn_produto is not null and cn_servico is null) or
    (ca_tipo = 'SERVICO' and cn_servico is not null and cn_produto is null)
  )
);

create index if not exists idx_ord_item_os_1
  on ord_item_os (cn_ordem_servico);

create index if not exists idx_ord_item_os_2
  on ord_item_os (cn_produto);

create index if not exists idx_ord_item_os_3
  on ord_item_os (cn_servico);
