create table if not exists cad_unidade (
  cn_unidade integer generated by default as identity primary key,
  an_descr text not null,
  ca_sigla text not null,
  dt_inc   timestamptz not null default now(),
  dt_alt   timestamptz not null default now(),
  constraint ck_cad_unidade_1 check (ca_sigla ~ '^[A-Z0-9]{1,10}$')
);

create unique index if not exists idx_cad_unidade_1
  on cad_unidade (lower(btrim(an_descr)));

create unique index if not exists idx_cad_unidade_2
  on cad_unidade (ca_sigla);
