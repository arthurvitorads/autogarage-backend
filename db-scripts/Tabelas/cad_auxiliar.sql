create table if not exists cad_auxiliar (
  cn_cadastro  integer generated by default as identity primary key,
  ca_tipo      text not null check (ca_tipo in ('CATEGORIA_PRODUTO', 'CATEGORIA_SERVICO', 'MARCA', 'UNIDADE')),
  an_descr     text not null,
  ca_sigla     text not null default '',
  dt_inc       timestamptz not null default now(),
  dt_alt       timestamptz not null default now(),
  constraint ck_cad_auxiliar_1 check (ca_tipo <> 'UNIDADE' or ca_sigla ~ '^[A-Z0-9]{1,10}$')
);

create unique index if not exists idx_cad_auxiliar_1
  on cad_auxiliar (ca_tipo, lower(btrim(an_descr)));

create unique index if not exists idx_cad_auxiliar_2
  on cad_auxiliar (ca_sigla) where ca_tipo = 'UNIDADE';
