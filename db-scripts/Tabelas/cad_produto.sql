create table if not exists cad_produto (
  cn_produto      integer generated by default as identity primary key,
  an_nome         text not null,
  an_referencia   text not null default '',
  an_categoria    text not null default '',
  an_marca        text not null default '',
  ca_unidade      text not null,
  vl_custo        numeric(11,2) not null check (vl_custo >= 0),
  vl_venda        numeric(11,2) not null check (vl_venda >= 0),
  qt_estoque      numeric(12,3) not null check (qt_estoque >= 0),
  qt_estoque_min  numeric(12,3) not null check (qt_estoque_min >= 0),
  an_obs          text not null default '',
  bo_sts_reg      boolean not null default true,
  dt_inc          timestamptz not null default now(),
  dt_alt          timestamptz not null default now()
);

create unique index if not exists idx_cad_produto_1
  on cad_produto (lower(an_referencia)) where an_referencia <> '';

create index if not exists idx_cad_produto_2
  on cad_produto (an_nome);
