create table if not exists ord_ordem_servico (
  cn_ordem_servico  bigint generated by default as identity primary key,
  nu_numero         integer generated by default as identity not null unique,
  cn_pessoa         bigint not null,
  cn_status_os      bigint not null,
  dt_entrada        timestamptz not null,
  dt_previsao       timestamptz,
  ca_status text not null default 'ABERTO' check (ca_status in ('ABERTO', 'EM_ANDAMENTO', 'FINALIZADO', 'CANCELADO')),
  an_motivo_cancelamento text not null default '',
  dt_inicio timestamptz,
  dt_finalizacao timestamptz,
  dt_cancelamento timestamptz,
  an_responsavel    text not null default '',
  an_placa          text not null check (an_placa ~ '^[A-Z]{3}[0-9][A-Z0-9][0-9]{2}$'),
  an_marca          text not null,
  an_modelo         text not null,
  nu_ano            integer check (nu_ano between 1900 and 9999),
  an_cor            text not null default '',
  qt_quilometragem  integer check (qt_quilometragem between 0 and 9999999),
  an_solicitacao    text not null default '',
  an_obs            text not null default '',
  dt_inc            timestamptz not null default now(),
  dt_alt            timestamptz not null default now(),
  constraint fk_ord_ordem_servico_1 foreign key (cn_pessoa) references cad_pessoa (cn_pessoa) on delete restrict on update cascade,
  constraint fk_ord_ordem_servico_2 foreign key (cn_status_os) references ord_status_os (cn_status_os) on delete restrict on update cascade,
  constraint ck_ord_ordem_servico_1 check (dt_previsao is null or dt_previsao >= dt_entrada)
);

create index if not exists idx_ord_ordem_servico_1
  on ord_ordem_servico (cn_pessoa);

create index if not exists idx_ord_ordem_servico_2
  on ord_ordem_servico (cn_status_os);
