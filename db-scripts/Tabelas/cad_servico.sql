create table if not exists cad_servico (
  cn_servico         integer generated by default as identity primary key,
  an_nome            text not null,
  an_categoria       text not null default '',
  vl_preco           numeric(11,2) not null check (vl_preco >= 0),
  nu_tempo_estimado  integer check (nu_tempo_estimado between 1 and 999999),
  an_obs             text not null default '',
  bo_sts_reg         boolean not null default true,
  dt_inc             timestamptz not null default now(),
  dt_alt             timestamptz not null default now()
);

create index if not exists idx_cad_servico_1
  on cad_servico (an_nome);
