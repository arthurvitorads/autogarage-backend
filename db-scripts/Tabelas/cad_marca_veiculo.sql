create table if not exists cad_marca_veiculo (
  cn_marca_veiculo integer generated by default as identity primary key,
  an_descr text not null,
  ca_chave text not null unique
);

comment on column cad_marca_veiculo.cn_marca_veiculo is 'Identificador da marca do veículo.';
comment on column cad_marca_veiculo.an_descr is 'Nome de exibição da marca do veículo.';
comment on column cad_marca_veiculo.ca_chave is 'Nome normalizado usado para identificar a marca.';
