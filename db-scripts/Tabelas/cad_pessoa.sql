create table cad_pessoa (
  cn_pessoa       bigint generated by default as identity primary key,
  ca_tipo         text not null check (ca_tipo in ('PF', 'PJ')),
  an_nome         text,
  ca_cpf          text,
  ca_cnpj         text,
  an_razao_social text,
  an_nome_fantasia text,
  an_email         text,
  an_telefone      text,
  bo_categ_cliente boolean not null default true,
  bo_categ_func   boolean not null default false,
  an_cargo        text,
  nm_comissao_percentual numeric(5, 2) default 0
    check (nm_comissao_percentual between 0 and 100),
  bo_sts_reg      boolean not null default true,
  dt_inc          timestamptz not null default now(),
  dt_alt          timestamptz not null default now()
);

create unique index if not exists idx_cad_pessoa_1
  on cad_pessoa (ca_cpf)
  where ca_cpf is not null and ca_cpf <> '';

create unique index if not exists idx_cad_pessoa_2
  on cad_pessoa (ca_cnpj)
  where ca_cnpj is not null and ca_cnpj <> '';

create index if not exists idx_cad_pessoa_3
  on cad_pessoa (dt_inc);
